const {chromium}=require('playwright');
const fs=require('fs');
const assert=require('assert');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 fs.mkdirSync('test-results',{recursive:true});
 try{
  await page.goto('http://127.0.0.1:8765/');
  await page.locator('#login').waitFor();
  assert(await page.locator('body').evaluate(el=>el.classList.contains('auth')));
  await page.locator('#login input[name=email]').fill('ui@example.com');
  await page.locator('#login input[name=password]').fill('browser-test-password-123');
  await page.locator('#login button').click();
  await page.getByRole('heading',{name:'Business overview',exact:true}).waitFor();
  assert.equal(await page.locator('.metric').count(),8);
  await page.screenshot({path:'test-results/dashboard-desktop.png',fullPage:true});
  await page.locator('#nav [data-page=customers]').click();
  await page.locator('#new').click();
  await page.locator('#record input[name=name]').fill('Browser customer');
  await page.locator('#record button').first().click();
  await page.getByRole('cell',{name:'Browser customer',exact:true}).waitFor();
  await page.locator('[data-copy]').first().click();
  await page.locator('#record input[name=name]').fill('Duplicated customer');
  await page.locator('#record button').first().click();
  await page.getByRole('cell',{name:'Duplicated customer',exact:true}).waitFor();
  await page.locator('#search').fill('Duplicated');
  assert.equal(await page.locator('#list tbody tr').count(),1);
  await page.locator('#nav [data-page=financial_statements]').click();
  await page.getByRole('heading',{name:'Financial statements',exact:true}).waitFor();
  await page.locator('#nav [data-page=tax_organizer]').click();
  await page.getByRole('heading',{name:'Guided tax organizer',exact:true}).waitFor();
  await page.locator('#nav [data-page=deployment]').click();
  await page.getByRole('heading',{name:'Deployment, installation & commissioning',exact:true}).waitFor();
  assert.equal(await page.locator('[data-platform-operation]:disabled').count(),4);
  await page.locator('#nav [data-page=capabilities]').click();
  await page.getByRole('heading',{name:'Capability catalog',exact:true}).waitFor();
  await page.locator('#capability-search').fill('Inventory valuation');
  assert.equal(await page.locator('[data-feature]:visible').count(),1);
  await page.locator('#logout').click();
  await page.locator('#login').waitFor();
  await page.setViewportSize({width:390,height:844});
  assert(await page.locator('#login').isVisible());
  assert(await page.locator('aside').isHidden());
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  await page.screenshot({path:'test-results/signin-mobile.png',fullPage:true});
  await page.goto('http://127.0.0.1:8765/register');
  await page.locator('#registration input[name=company]').fill('Browser tenant');
  await page.locator('#registration input[name=email]').fill('tenant-browser@example.com');
  await page.locator('#registration input[name=password]').fill('tenant-browser-password-123');
  await page.locator('#registration input[name=confirm_password]').fill('tenant-browser-password-123');
  await page.locator('#registration button').click();
  await page.getByRole('heading',{name:'Business overview',exact:true}).waitFor();
  await page.locator('#nav-toggle').click();
  await page.locator('#nav [data-page=payroll_processing]').click();
  await page.getByRole('heading',{name:'Provider payroll setup required',exact:true}).waitFor();
  assert.equal(errors.length,0,errors.join('; '));
  process.stdout.write('Desktop and mobile GUI smoke checks passed\n');
 }catch(error){await page.screenshot({path:'test-results/failure.png',fullPage:true});throw error}
 finally{await browser.close()}
})().catch(error=>{process.stderr.write(error.stack+'\n');process.exit(1)});
